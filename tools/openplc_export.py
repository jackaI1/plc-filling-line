"""Use OpenPLC v3's actual PLCopen LD→ST generator without its GUI.

Only its translation-catalog UI dependency is replaced by identity translation.
The PLC parser, type library and program generator are upstream, unmodified.
"""
import argparse
import contextlib
import gettext
import io
from pathlib import Path
import subprocess
import sys
import types

ROOT = Path(__file__).resolve().parents[1]
REV = "6a8e930a914e4421e8fa05966b31eb371b439243"


def editor_checkout(existing=None):
    directory = Path(existing).resolve() if existing else ROOT / ".build/editor"
    if not (directory / "PLCGenerator.py").exists():
        directory.parent.mkdir(exist_ok=True)
        def git(*args):
            subprocess.run(["git", *args], cwd=directory, check=True)
        directory.mkdir(exist_ok=True)
        if not (directory / ".git").exists():
            git("init")
            git("remote", "add", "origin", "https://github.com/thiagoralves/editor.git")
        git("fetch", "--depth", "1", "--filter=blob:none", "origin", REV)
        git("sparse-checkout", "set", "--no-cone", "/PLCGenerator.py", "/plcopen/", "/xmlclass/", "/util/")
        git("checkout", "--detach", "FETCH_HEAD")
    actual = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=directory, text=True).strip()
    if actual != REV:
        raise ValueError("OpenPLC editor revision differs from pinned revision")
    return directory


def export(path, editor=None):
    # Validate our supported graph before passing it to upstream code.
    from tools.ladder import compile_ld
    compile_ld(path)
    directory = editor_checkout(editor)
    sys.path.insert(0, str(directory))
    gettext.install("fillingline")
    translations = types.ModuleType("util.TranslationCatalogs")
    translations.NoTranslate = lambda value: value
    sys.modules["util.TranslationCatalogs"] = translations
    from plcopen import LoadProject
    from plcopen.structures import StdBlckDct
    from PLCGenerator import ProgramGenerator

    class Controller:
        def GetBaseType(self, name):
            return name

        def GetBlockType(self, name, inputs=None):
            if name not in {"TON", "CTU", "R_TRIG"}:
                raise ValueError(f"Unsupported block: {name}")
            return StdBlckDct[name][0][1]

        def GetConfigurationExtraVariables(self):
            return []

    project, error = LoadProject(str(path))
    if error:
        raise ValueError(str(error))
    # The XML addresses define the simulated panel's terminal schedule. Native
    # host I/O is passed by value through bridge.c, not mapped to PLC hardware.
    # IEC VAR_INPUT/VAR_OUTPUT parameters cannot carry AT locations in matiec.
    # Remove only address metadata from the in-memory export model; preserve
    # names, logic and the canonical XML used by the drawing and tag checks.
    for variable in project.xpath(
            "//*[local-name()='interface']/*[local-name()='inputVars' or local-name()='outputVars']"
            "/*[local-name()='variable'][@address]"):
        variable.attrib.pop("address")
    errors, warnings = [], []
    generator = ProgramGenerator(Controller(), project, errors, warnings)
    # Upstream includes verbose debug prints for parallel contact paths.
    with contextlib.redirect_stdout(io.StringIO()):
        generator.GenerateProgram(lambda _: None)
    if errors or warnings:
        raise ValueError(str(errors + warnings))
    return f"(* Generated by OpenPLC editor {REV}; source: plc/line.xml. *)\n" + "".join(
        text for text, _ in generator.GetGeneratedProgram())


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--editor")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Script execution and module execution share the same import root.
    sys.path.insert(0, str(ROOT))
    result = export(ROOT / "plc/line.xml", args.editor)
    output = ROOT / "plc/line.st"
    if args.check:
        if output.read_text() != result:
            raise SystemExit("line.st is stale: python3 tools/openplc_export.py")
    else:
        output.write_text(result)
    print("OpenPLC ladder export verified")
